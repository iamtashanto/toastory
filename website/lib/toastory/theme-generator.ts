export function generateThemeCss(t: ThemeDefinition): string {
  const selector = `[data-gk-theme="${t.name}"]`;
  const baseTokens = `
    --gk-radius: ${t.radius};
    --gk-blur: ${t.blur};
    --gk-saturate: ${t.saturate};
    ${t.borderWidth ? `--gk-border-w: ${t.borderWidth};` : ''}
    ${t.font ? `--gk-font: ${t.font};` : ''}
    ${t.ease ? `--gk-ease: ${t.ease};` : ''}
    ${t.duration ? `--gk-duration: ${t.duration};` : ''}
  `;

  const tokenProps = (tokens: ThemeTokens) => `
    --gk-bg: ${tokens.bg};
    --gk-bg-solid: ${tokens.solid};
    --gk-fg: ${tokens.fg};
    --gk-muted: ${tokens.muted};
    --gk-border: ${tokens.border};
    --gk-shadow: ${tokens.shadow};
    --gk-accent: ${tokens.accent};
    --gk-accent-fg: ${tokens.accentFg};
    --gk-danger: ${tokens.danger};
    --gk-danger-fg: ${tokens.dangerFg};
    --gk-success: ${tokens.success};
    --gk-error: ${tokens.error};
    --gk-warning: ${tokens.warning};
    --gk-info: ${tokens.info};
  `;

  return `
/* Theme: ${t.name} */
${selector} {
  color-scheme: light;
  ${baseTokens}
  ${tokenProps(t.light)}
}

${selector}[data-gk-mode="dark"],
:is(.dark, [data-theme="dark"]) ${selector} {
  color-scheme: dark;
  ${tokenProps(t.dark)}
}

@media (prefers-color-scheme: dark) {
  ${selector}[data-gk-mode="auto"] {
    color-scheme: dark;
    ${tokenProps(t.dark)}
  }
}
${t.css ? t.css.replace(/&/g, selector) : ''}
`;
}

